package io.yupiik.fusion.a2a.model;

import io.yupiik.fusion.framework.build.api.configuration.Property;
import io.yupiik.fusion.framework.build.api.json.JsonModel;
import java.util.List;
import java.util.Map;

/**
 * The core unit of action of A2A: a stateful piece of work with a lifecycle.
 * <p>
 * This is the immutable <em>snapshot</em> a client gets. The mutable server side state lives in
 * {@code io.yupiik.fusion.a2a.service.A2ATask}.
 *
 * @param id        the task identifier, always generated by the server.
 * @param contextId the conversation this task belongs to.
 * @param status    where the task stands.
 * @param artifacts the outputs produced so far, it is {@code null} when the client asked not to get them.
 * @param history   the messages exchanged, truncated to the requested {@code historyLength}.
 * @param metadata  free form metadata.
 */
@JsonModel
public record Task(
        @Property(documentation = "The task identifier, always generated by the server.")
        String id,

        @Property(documentation = "The conversation this task belongs to.")
        String contextId,

        @Property(documentation = "Where the task stands.") TaskStatus status,

        @Property(documentation = "The outputs produced so far, it is null when the client asked not to get them.")
        List<Artifact> artifacts,

        @Property(documentation = "The messages exchanged, truncated to the requested historyLength.")
        List<Message> history,

        @Property(documentation = "Free form metadata.") Map<String, Object> metadata) {}
