package io.yupiik.fusion.a2a.model;

import static java.util.stream.Collectors.joining;

import io.yupiik.fusion.framework.build.api.configuration.Property;
import io.yupiik.fusion.framework.build.api.json.JsonModel;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.UUID;
import java.util.stream.Stream;

/**
 * One unit of communication between two agents.
 * <p>
 * Messages carry the <em>conversation</em>: the client sends one to start or continue a task and the agent sends one
 * back to ask something or to answer directly. Task <em>outputs</em> belong to {@link Artifact}s, not to messages -
 * see section 3.7 of the specification.
 *
 * @param messageId        the identifier of the message, generated by its author.
 * @param contextId        the conversation this message belongs to, it can be {@code null} on a client message.
 * @param taskId           the task this message belongs to, it can be {@code null} to start a new one.
 * @param role             who sent it.
 * @param parts            the content, there must be at least one part.
 * @param metadata         free form metadata, this is also where {@code skillId} can be passed to route the message.
 * @param extensions       the URIs of the extensions which contributed to this message.
 * @param referenceTaskIds the tasks this message refers to for additional context.
 */
@JsonModel
public record Message(
        @Property(documentation = "The identifier of the message, generated by its author.")
        String messageId,

        @Property(documentation = "The conversation this message belongs to, it can be null on a client message.")
        String contextId,

        @Property(documentation = "The task this message belongs to, it can be null to start a new one.")
        String taskId,

        @Property(documentation = "Who sent it.") Role role,

        @Property(documentation = "The content, there must be at least one part.")
        List<Part> parts,

        @Property(documentation = "Free form metadata, this is also where skillId can be passed to route the message.")
        Map<String, Object> metadata,

        @Property(documentation = "The URIs of the extensions which contributed to this message.")
        List<String> extensions,

        @Property(documentation = "The tasks this message refers to for additional context.")
        List<String> referenceTaskIds) {
    /**
     * @param texts the text parts of the message.
     * @return an agent message with a generated identifier, i.e. what an agent answers.
     */
    public static Message agent(final String... texts) {
        return of(Role.ROLE_AGENT, Stream.of(texts).map(Part::text).toList());
    }

    /**
     * @param texts the text parts of the message.
     * @return a user message with a generated identifier, i.e. what a client sends - mainly useful in tests.
     */
    public static Message user(final String... texts) {
        return of(Role.ROLE_USER, Stream.of(texts).map(Part::text).toList());
    }

    /**
     * @param role  who sends the message.
     * @param parts its content.
     * @return the message, with a generated {@code messageId}.
     */
    public static Message of(final Role role, final List<Part> parts) {
        return new Message(UUID.randomUUID().toString(), null, null, role, parts, null, null, null);
    }

    /**
     * @return all the text parts joined with a new line, an empty string when there is none.
     */
    public String text() {
        return parts == null
                ? ""
                : parts.stream().map(Part::text).filter(Objects::nonNull).collect(joining("\n"));
    }

    /**
     * @return the value of the first {@code data} part, {@code null} when there is none.
     */
    public Object data() {
        return parts == null
                ? null
                : parts.stream()
                        .map(part -> part.data())
                        .filter(Objects::nonNull)
                        .findFirst()
                        .orElse(null);
    }

    /**
     * @param contextId the conversation to attach this message to.
     * @param taskId    the task to attach this message to, it can be {@code null}.
     * @return a copy of this message bound to {@code contextId}/{@code taskId}.
     */
    public Message boundTo(final String contextId, final String taskId) {
        if (Objects.equals(this.contextId, contextId) && Objects.equals(this.taskId, taskId)) {
            return this;
        }
        return new Message(
                messageId == null ? UUID.randomUUID().toString() : messageId,
                contextId,
                taskId,
                role,
                parts,
                metadata,
                extensions,
                referenceTaskIds);
    }
}
