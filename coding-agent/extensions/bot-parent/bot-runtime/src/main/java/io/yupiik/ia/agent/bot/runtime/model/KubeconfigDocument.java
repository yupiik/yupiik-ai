package io.yupiik.ia.agent.bot.runtime.model;

import io.yupiik.fusion.framework.build.api.configuration.Property;
import io.yupiik.fusion.framework.build.api.json.JsonModel;
import java.util.List;
import java.util.Map;

/** Authentication-only projection, checked before Fusion reads the complete kubeconfig. */
@JsonModel
public record KubeconfigDocument(
        @Property(documentation = "Configured cluster identities.")
        List<User> users) {
    @JsonModel
    public record User(
            @Property(documentation = "Static authentication attributes; external plugins are forbidden.")
            Map<String, Object> user) {}
}
